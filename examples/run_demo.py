"""Run Cognis against a reproducible sample agent and write a Markdown report."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.engine.evaluator import run_evaluation
from examples.recruiter_scenario import RECRUITER_SCENARIO
from examples.sample_agent import SampleSupportAgent


def render_report(result: dict) -> str:
    metrics = result.get("metrics") or {}
    cases = result.get("results", [])
    total = result.get("total", len(cases))
    passed = result.get("passed", sum(1 for case in cases if case.get("passed")))
    failed = result.get("failed", total - passed)
    rate = result.get("pass_rate", (passed / total if total else 0.0))
    security = [case for case in cases if "security" in case.get("tags", [])]
    security_passed = sum(1 for case in security if case.get("passed"))
    lines = [
        "# Cognis Demo Evaluation Report", "",
        "> Generated by running the deterministic sample agent against the committed recruiter scenario. "
        "Latency values vary by machine and run; pass/fail behavior is designed to be reproducible.", "",
        "## Summary", "",
        f"- **Evaluation ID:** `{result.get('evaluation_id', 'not available')}`",
        f"- **Suite:** `{result.get('suite', 'recruiter_demo')}`",
        f"- **Status:** **{result.get('status', 'unknown').upper()}**",
        f"- **Pass rate:** **{passed}/{total} ({rate * 100:.1f}%)**",
        f"- **Failures:** **{failed}**",
        f"- **Security checks:** **{security_passed}/{len(security)} passed**", "",
        "## Latency", "", "| Metric | Milliseconds |", "|---|---:|",
        f"| Mean | {metrics.get('latency_mean_ms', 'n/a')} |",
        f"| p50 | {metrics.get('latency_p50_ms', 'n/a')} |",
        f"| p95 | {metrics.get('latency_p95_ms', 'n/a')} |",
        f"| Maximum | {metrics.get('latency_max_ms', 'n/a')} |", "",
        "## Case results", "",
        "| Case | Category | Result | Expected | Actual | Latency (ms) |",
        "|---|---|---|---|---|---:|",
    ]
    for case in cases:
        categories = ", ".join(case.get("tags", []))
        status = "PASS" if case.get("passed") else "FAIL"
        expected = str(case.get("expected", "")).replace("|", "\\|").replace("\n", " ")
        actual = str(case.get("actual", "")).replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {case.get('case_id', 'unknown')} | {categories} | {status} | "
                     f"{expected} | {actual} | {case.get('duration_ms', 0)} |")
    failures = [case for case in cases if not case.get("passed")]
    lines.extend(["", "## Failure details", ""])
    if not failures:
        lines.append("No failed cases.")
    else:
        for case in failures:
            lines.append(f"- **{case.get('case_id')}** — expected `{case.get('expected')}`, got `{case.get('actual')}`.")
            for assertion in case.get("assertions", []):
                if not assertion.get("passed"):
                    lines.append(f"  - `{assertion.get('name')}`: {assertion.get('message')}")
    lines.extend([
        "", "## Interpretation and limitations", "",
        "- This suite has six hand-written cases; it is a reproducible smoke/regression demo, not a benchmark.",
        "- The sample agent is deterministic Python logic, not a hosted LLM. No provider API key or network access is required.",
        "- Prompt-injection and canary checks cover only the specific fixtures in this suite; they do not prove an agent is secure.",
        "- Latency is measured locally and should be compared only under similar hardware/load conditions.", "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("reports/demo-report.md"), help="Markdown report output path")
    parser.add_argument("--json-output", type=Path, default=Path("reports/demo-report.json"), help="Raw JSON result output path")
    args = parser.parse_args()
    response = run_evaluation(SampleSupportAgent(), RECRUITER_SCENARIO, include_traces=True)
    result = response.model_dump(mode="json")
    markdown = render_report(result)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(markdown, encoding="utf-8")
    args.json_output.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(markdown)
    print(f"\nReports written to: {args.output} and {args.json_output}")
    return 0 if response.status == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
